  const SKIP = '.md, .ububble, .texhl, .texerr code, #pdf-title, #pdf-meta, .nprev, .src .st, .src .ss, .searchline .q, .iq, .diff, .ibody, .ihead b, .docinfo b, #rv-select, #rv-src, #p-sum, pre, code, textarea, .katex, #guide-body, .attchip .nm, .paperitem b, #lib-body td:nth-child(3) b, #lib-body td.k, #fs-list, #fs-path, .projtag, script, style, [data-noi18n]';
  const ORIG = new WeakMap();
  let LANG = 'en', busy = false, obs;
  try { LANG = localStorage.getItem('ui_lang') || ((navigator.language || '').toLowerCase().startsWith('vi') ? 'vi' : 'en'); } catch {}

  function tr(s) {
    if (LANG !== 'vi' || !s || typeof s !== 'string') return s;
    const k = s.trim(); if (!k) return s;
    if (Object.prototype.hasOwnProperty.call(VI, k)) return s.replace(k, VI[k]);
    for (const [re, rep] of PATTERNS) if (re.test(k)) return s.replace(k, k.replace(re, rep));
    return s;
  }
  function skipEl(el) { return !el || (el.closest && el.closest(SKIP)); }
  function doText(n) {
    if (skipEl(n.parentElement)) return;
    if (!ORIG.has(n)) ORIG.set(n, n.nodeValue);
    const orig = ORIG.get(n), want = LANG === 'vi' ? tr(orig) : orig;
    if (n.nodeValue !== want) n.nodeValue = want;
  }
  function doAttrs(el) {
    if (el.matches('textarea, input') ? skipEl(el.parentElement) : skipEl(el)) return;  // placeholders of inputs are UI, their values are not
    for (const a of ['placeholder', 'title']) {
      if (!el.hasAttribute(a)) continue;
      const key = 'data-i18n-' + a;
      if (!el.hasAttribute(key)) el.setAttribute(key, el.getAttribute(a));
      const orig = el.getAttribute(key), want = LANG === 'vi' ? tr(orig) : orig;
      if (el.getAttribute(a) !== want) el.setAttribute(a, want);
    }
  }
  function walk(root) {
    if (!root) return;
    if (root.nodeType === 3) { doText(root); return; }
    if (root.nodeType !== 1 || skipEl(root)) return;
    doAttrs(root);
    const tw = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
      acceptNode: n => n.nodeType === 1 ? (skipEl(n) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT) : NodeFilter.FILTER_ACCEPT});
    let n; while ((n = tw.nextNode())) { if (n.nodeType === 3) doText(n); else doAttrs(n); }
    root.querySelectorAll('textarea[placeholder], input[placeholder], textarea[title], input[title]').forEach(doAttrs);
  }
